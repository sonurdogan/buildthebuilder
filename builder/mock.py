"""The bank's services as a Cloudflare Worker, written from the material and checked against the bank's
own test data before the builder relies on it.

    write_worker(material, api)  -> worker source + the test requests that prove it
    deploy(name, source, folder) -> the workers.dev URL
    check(url, tests)            -> list of failures
The worker also serves the operations it implements at GET /__builder/api.json, so the agent builder
uses exactly the paths and fields the mock serves."""
import json, os, pathlib, re, subprocess, urllib.error, urllib.request

from . import llm, trace
from .pack import SYSTEM

META_PATH = "/__builder/api.json"

WRAPPER = """// Generated by the builder from the bank's material. Do not edit by hand.
const BUILDER_API = __API__;
// The bank's test data files, verbatim: { "relative/path.json": <parsed content> }
const DATA = __DATA__;

__CODE__

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (url.pathname === "__META__") {
      return new Response(JSON.stringify(BUILDER_API), { headers: { "content-type": "application/json" } });
    }
    try {
      return await handleBank(request, env);
    } catch (e) {
      return new Response(JSON.stringify({ error: "mock_failure", detail: String(e) }), {
        status: 500, headers: { "content-type": "application/json" } });
    }
  },
};
"""


def _prompt(material, api, data_names=()):
    return f"""<material>
{material}
</material>

<operations>
{json.dumps(api, indent=1, ensure_ascii=False)}
</operations>

Write the bank's services as JavaScript for a Cloudflare Worker (ES module). Define exactly one function
`async function handleBank(request, env)` that returns a `Response`; I wrap it with the export myself.
- Implement every operation above: same method, path, field names, request and response shapes, HTTP status.
- For the bank's test customers return exactly the answers the test data lists, status included, and wait
  the delay it lists. The test data files are already embedded, verbatim and parsed, as the constant
  `DATA` = {{"<relative path of the json file>": <content>}} (files: {list(data_names)}). Read them from
  `DATA` at request time; never copy them into your code. Look at the material to see their structure.
  A description inside the data can name keys differently from the records themselves (another language,
  an older version): the keys the records actually use win. Handle every variant you see (for example a
  delay or a response body given under either name). Follow the test-environment rules of the material (unknown
  customers, invalid input, which calls fail and how, response times only if they matter).
- Validate requests the way the integration document says (missing or wrong fields give its documented error).
- Keep it stateless: a write returns its documented success answer and does not change later reads,
  unless the test-environment rules say otherwise.
- Unknown paths: 404 with a JSON body. Always send `content-type: application/json`.
- Accept path params and query params case-sensitively as documented; trim whitespace in values.

Also write the test requests that prove it: at least one per operation and test customer behaviour that
the material lists (success, each documented error, each special test customer).

Return one JSON object: {{"code": "...javascript...", "tests": [{{"name": "...", "method": "GET", "path": "/...?a=b",
"headers": {{}}, "body": null, "status": 200, "body_contains": {{"field": "expected value"}}}}]}}
`body_contains` lists fields (dot paths allowed, e.g. "cards.0.cardNumber") whose exact values the
material gives."""


def write_worker(material, api, data_names=(), failures=None, previous=None):
    p = _prompt(material, api, data_names)
    if failures:
        p += f"""

Your previous code:
<code>
{previous}
</code>
These tests failed against the deployed worker:
{json.dumps(failures, indent=1, ensure_ascii=False)}
Fix the code (if a test itself contradicts the material, fix the test instead). Return the whole object again."""
    out = llm.ask_json(p, "write the mock bank worker" + (" (repair)" if failures else ""), system=SYSTEM)
    return out["code"], out.get("tests") or []


def source(code, api, data):
    api_js = json.dumps(api, ensure_ascii=False)
    data_js = json.dumps(data, ensure_ascii=False)
    return (WRAPPER.replace("__META__", META_PATH).replace("__API__", api_js).replace("__CODE__", code)
            .replace("__DATA__", data_js))


def deploy(name, src, folder):
    folder = pathlib.Path(folder)
    (folder / "src").mkdir(parents=True, exist_ok=True)
    (folder / "src" / "index.js").write_text(src, encoding="utf-8")
    (folder / "wrangler.toml").write_text(
        f'name = "{name}"\nmain = "src/index.js"\ncompatibility_date = "2026-09-01"\n', encoding="utf-8")
    p = subprocess.run("npx wrangler deploy", cwd=folder, shell=True, capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    out = p.stdout + p.stderr
    m = re.search(r"https://[a-zA-Z0-9.\-]+\.workers\.dev", out)
    tr = trace.current()
    if tr:
        tr.event("mock_deployed", name=name, ok=p.returncode == 0, url=m.group(0) if m else None, log=out[-1500:])
    if p.returncode != 0 or not m:
        raise RuntimeError("wrangler deploy failed:\n" + out[-3000:])
    return m.group(0)


def _get(obj, path):
    cur = obj
    for k in path.split("."):
        if isinstance(cur, list) and k.isdigit() and int(k) < len(cur):
            cur = cur[int(k)]
        elif isinstance(cur, dict) and k in cur:
            cur = cur[k]
        else:
            return "<missing>"
    return cur


def call(base, method, path, headers=None, body=None):
    data = json.dumps(body).encode() if body is not None else None
    h = {"content-type": "application/json", "User-Agent": "Mozilla/5.0 (builder-selftest)", **(headers or {})}
    req = urllib.request.Request(base.rstrip("/") + path, data=data, headers=h, method=method)
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            status, raw = r.status, r.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        status, raw = e.code, e.read().decode("utf-8", "replace")
    try:
        return status, json.loads(raw)
    except Exception:
        return status, raw


def check(base, tests):
    fails = []
    for t in tests:
        try:
            status, body = call(base, t.get("method", "GET"), t["path"], t.get("headers"), t.get("body"))
        except Exception as e:
            fails.append({**t, "error": str(e)})
            continue
        bad = []
        if t.get("status") is not None and status != t["status"]:
            bad.append(f"status {status} != {t['status']}")
        for k, v in (t.get("body_contains") or {}).items():
            got = _get(body, k)
            if str(got) != str(v) and got != v:
                bad.append(f"{k}: {got!r} != {v!r}")
        if bad:
            fails.append({"name": t.get("name"), "method": t.get("method"), "path": t["path"], "body": t.get("body"),
                          "problems": bad, "got": body if len(json.dumps(body, default=str)) < 1500 else str(body)[:1500]})
    tr = trace.current()
    if tr:
        tr.event("mock_selftest", url=base, tests=len(tests), failed=[f.get("name") for f in fails])
    return fails


def fetch_api(base):
    status, body = call(base, "GET", META_PATH)
    if status != 200 or not isinstance(body, dict):
        raise RuntimeError(f"mock at {base} does not serve {META_PATH}")
    return body
